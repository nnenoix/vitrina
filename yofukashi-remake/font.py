def _build():
    out = {}
    for ch, rows in _G.items():
        w = max(len(r) for r in rows) if rows else 3
        m = np.zeros((9, w), bool)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    m[y, x] = True
        if ch != ' ':
            cols = np.where(m.any(axis=0))[0]
            if len(cols):
                m = m[:, cols.min():cols.max() + 1]
        out[ch] = m
    return out


GLYPHS = _build()


def text_width(s, spacing=1):
    w = 0
    for ch in s:
        w += GLYPHS.get(ch, GLYPHS[' ']).shape[1] + spacing
    return max(0, w - spacing)


def render_mask(s, spacing=1, bold=False):
    """Return a boolean mask (9 x width) for string s."""
    w = text_width(s, spacing) + (len(s) if bold else 0)
    m = np.zeros((9, max(w, 1)), bool)
    x = 0
    for ch in s:
        g = GLYPHS.get(ch, GLYPHS[' '])
        m[:, x:x + g.shape[1]] |= g
        if bold:
            m[:, x + 1:x + 1 + g.shape[1]] |= g
        x += g.shape[1] + spacing + (1 if bold else 0)
    return m


def wrap(text, max_px, spacing=1):
    words = text.split(' ')
    lines, cur = [], ''
    for w in words:
        t = (cur + ' ' + w) if cur else w
        if text_width(t, spacing) <= max_px or not cur:
            cur = t
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines
